# ---------------------------------------------------------------- Hangul ---
BASE, NV, NT = 0xAC00, 21, 28
A, AE, YA, YAE, EO, E, YEO, O, WA, WAE, OE, U, WO, WI, EU, UI, I = (
    0, 1, 2, 3, 4, 5, 6, 8, 9, 10, 11, 13, 14, 16, 18, 19, 20)
T_NONE, T_N, T_D, T_L, T_B, T_S, T_SS, T_H = 0, 4, 7, 8, 17, 19, 20, 27


def dec(ch):
    n = ord(ch) - BASE
    return n // (NV * NT), (n // NT) % NV, n % NT


def com(l, v, t=0):
    return chr(BASE + (l * NV + v) * NT + t)


def set_final(s, t):
    l, v, _ = dec(s[-1])
    return s[:-1] + com(l, v, t)


def final(s):
    return dec(s[-1])[2]


def vowel(s):
    return dec(s[-1])[1]


def bright(v):
    return v in (A, YA, O)


