def load_lemmas():
    lemmas, skipped = {}, []
    for n in range(1, 11):
        with open(os.path.join(CONTENT, "levels", f"L{n}.json"), encoding="utf-8") as f:
            for v in json.load(f)["vocab"]:
                t = v["t"]
                if not t.endswith("다"):
                    continue
                # Level vocab carries no pos; every 다-final item there today is
                # a 합니다체 expression. A bare dictionary form must be added by hand.
                assert t.endswith("니다"), f"unclassified dictionary form in L{n}: {t}"
                skipped.append((t, f"L{n} vocab: conjugated expression/phrase"))
    entries = {}
    for path in sorted(glob.glob(os.path.join(CONTENT, "vocab2", "out", "ev-*.json"))):
        with open(path, encoding="utf-8") as f:
            for e in json.load(f):
                entries[e["id"]] = e
    for path in sorted(glob.glob(os.path.join(CONTENT, "vocab2", "rev", "ev-*.json"))):
        with open(path, encoding="utf-8") as f:
            patch = json.load(f)
        for e in patch.get("fix", []):
            entries[e["id"]] = e
        for i in patch.get("drop", []):
            entries.pop(i, None)
    for e in entries.values():
        if e.get("pos") in ("verb", "adjective"):
            t = e["t"]["s"]
            if not t.endswith("다") or " " in t:
                skipped.append((t, "not a single dictionary form"))
            else:
                lemmas[t] = e["pos"]
    return lemmas, skipped


def build():
    lemmas, skipped = load_lemmas()
    table, classes = {}, {}
    for lemma, pos in lemmas.items():
        if lemma in EXCLUDE:
            skipped.append((lemma, EXCLUDE[lemma]))
            continue
        cls, row = conjugate(lemma, pos)
        if lemma in OVERRIDES:
            for k, v in OVERRIDES[lemma][0].items():
                if v is None:
                    row.pop(k, None)
                else:
                    row[k] = v
        assert len(row["note"].split()) <= 15, lemma
        table[lemma] = row
        classes[lemma] = cls
    stale = (set(OVERRIDES) | set(NO_VOLITION) | set(EXCLUDE)) - set(lemmas)
    assert not stale, f"tables name lemmas not in the course: {sorted(stale)}"
    return table, classes, skipped


if __name__ == "__main__":
    table, _, skipped = build()
    with open(os.path.join(HERE, "conj.json"), "w", encoding="utf-8") as f:
        json.dump(table, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print(f"{len(table)} lemmas written, {len(skipped)} skipped")
