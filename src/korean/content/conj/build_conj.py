# --------------------------------------------------------------- engine ---
def classify(stem):
    t, v = final(stem), vowel(stem)
    if stem.endswith("하"):
        return "hada"
    if t == T_B and stem in B_IRR:
        return "b"
    if t == T_D and stem in D_IRR:
        return "d"
    if t == T_S and stem in S_IRR:
        return "s"
    if t == T_H and stem in H_IRR:
        return "h"
    if t == T_L:
        return "l"
    if t:
        return "cons"
    if stem in REO_IRR:
        return "reo"
    if stem[-1] == "르" and len(stem) > 1 and stem not in EU_NOT_REU:
        return "reu"
    if v == EU:
        return "eu"
    return "vowel"


def eo(prev_vowel):
    return "아" if bright(prev_vowel) else "어"


def a_form(stem, cls):
    """The -아/어 infinitive (present = this + 요)."""
    if cls == "hada":
        return stem[:-1] + "해"
    if cls == "b":
        return set_final(stem, T_NONE) + "워"
    if cls == "d":
        return set_final(stem, T_L) + eo(vowel(stem))
    if cls == "s":
        return set_final(stem, T_NONE) + eo(vowel(stem))
    if cls == "h":
        l, v, _ = dec(stem[-1])
        return stem[:-1] + com(l, {A: AE, EO: AE, YA: YAE}[v])
    if cls in ("l", "cons"):
        return stem + eo(vowel(stem))
    if cls == "reo":
        return stem + "러"
    if cls == "reu":
        head = set_final(stem[:-1], T_L)
        return head + ("라" if bright(vowel(stem[:-1])) else "러")
    if cls == "eu":
        l, _, _ = dec(stem[-1])
        pv = vowel(stem[:-1]) if len(stem) > 1 else EO
        return stem[:-1] + com(l, A if bright(pv) else EO)
    # plain vowel stem
    l, v, _ = dec(stem[-1])
    if v in (A, EO, AE, E, YEO):
        return stem
    if stem in I_NO_CONTRACT or v in (WI, UI):
        return stem + "어"
    merged = {O: WA, U: WO, I: YEO, OE: WAE}[v]
    return stem[:-1] + com(l, merged)


def future_stem(stem, cls):
    """Stem joined with -(으)ㄹ, before ' 거예요'."""
    if cls == "l":
        return stem
    if cls == "b":
        return set_final(stem, T_NONE) + "울"
    if cls == "d":
        return set_final(stem, T_L) + "을"
    if cls == "s":
        return set_final(stem, T_NONE) + "을"
    if cls == "h":
        return set_final(stem, T_L)
    if cls == "cons":
        return stem + "을"
    return set_final(stem, T_L)


def please_form(stem, cls):
    if cls == "l":
        return set_final(stem, T_NONE) + "세요"
    if cls == "b":
        return set_final(stem, T_NONE) + "우세요"
    if cls == "d":
        return set_final(stem, T_L) + "으세요"
    if cls == "s":
        return set_final(stem, T_NONE) + "으세요"
    if cls == "cons":
        return stem + "으세요"
    return stem + "세요"


def past_of(af):
    return set_final(af, T_SS) + "어요"


AUTO_NOTE = {
    "b": "ㅂ irregular: ㅂ → 우 before vowel endings ({p}).",
    "d": "ㄷ irregular: ㄷ → ㄹ before vowel endings ({p}).",
    "s": "ㅅ irregular: ㅅ drops before vowels, no contraction ({p}).",
    "h": "ㅎ irregular: ㅎ drops and the vowel becomes ㅐ/ㅒ ({p}).",
    "l": "ㄹ stem: ㄹ drops before ㄴ/ㅂ/ㅅ ({x}).",
    "reu": "르 irregular: 르 → ㄹ라/ㄹ러 before 아/어 ({p}).",
    "reo": "러 irregular ({p}).",
    "eu": "으 irregular: ㅡ drops before 아/어 ({p}).",
}


def l_example(stem, row):
    """Forms showing the ㄹ drop: the -(으)세요 form, else adnominal + -ㅂ니다."""
    if "please" in row:
        return row["please"]
    bare = set_final(stem, T_NONE)
    adnominal = bare + "는" if row["pos"] == "verb" else set_final(stem, T_N)
    return f"{adnominal}, {set_final(stem, T_B)}니다"


def conjugate(lemma, pos):
    stem = lemma[:-1]
    cls = classify(stem)
    af = a_form(stem, cls)
    present = af + "요"
    row = {"pos": pos, "present": present, "past": past_of(af),
           "future": future_stem(stem, cls) + " 거예요"}
    root = stem[:-1]
    # Noun + 하다 / 되다 verbs put 안 before the light verb: 공부 안 해요, 해결 안 돼요.
    split_neg = ((cls == "hada" and pos == "verb" and lemma not in HADA_NO_SPLIT
                  and (len(root) >= 2 or lemma in HADA_SPLIT_MONO))
                 or (stem.endswith("되") and len(root) >= 2))
    row["neg"] = root + " 안 " + present[len(root):] if split_neg else "안 " + present
    if pos == "verb":
        row["want"] = stem + "고 싶어요"
        row["please"] = please_form(stem, cls)
        for key in NO_VOLITION.get(lemma, ()):
            del row[key]
    if cls in AUTO_NOTE:
        x = l_example(stem, row) if cls == "l" else ""
        note = AUTO_NOTE[cls].format(p=present, x=x)
    elif cls == "hada":
        note = ("하다 verb: neg splits, " + row["neg"] + ".") if " 안 해요" in row["neg"] else ""
    elif split_neg:
        note = f"되다 verb: neg splits, {row['neg']} (되 + 어요 → 돼요)."
    elif cls == "vowel" and af != stem + "어" and af != stem:
        note = f"Contraction: {stem[-1]} + {eo(vowel(stem))}요 → {af[-1]}요."
    else:
        note = ""
    row["note"] = note
    return cls, row


